import assert from 'node:assert/strict'
const base = process.env.BOOK_CHECK_URL || 'http://127.0.0.1:3007'
const listing = await fetch(base+'/blog',{redirect:'manual'})
assert.equal(listing.status,200,'blog must not redirect to Ghost')
const html=await listing.text()
assert.ok(html.includes('Ideas worth'),'server-rendered blog heading')
const search=await (await fetch(base+'/api/blog/search?pageSize=50')).json()
assert.ok(search.total>0,'existing Sanity articles are present')
assert.equal(search.posts.length,search.total,'all published article summaries returned')
assert.ok(search.posts.every(p=>!p._id.startsWith('drafts.')),'no drafts')
for(const post of search.posts){
 const response=await fetch(base+'/blog/'+post.slug.current)
 assert.equal(response.status,200,post.slug.current)
 const article=await response.text()
 assert.ok(article.includes('blog-prose'),post.slug.current+': body rendered')
 assert.equal((article.match(/<h1(?:\s|>)/g)||[]).length,1,post.slug.current+': one H1')
 const data=[...article.matchAll(/<script type="application\/ld\+json">(.*?)<\/script>/gs)].map(m=>JSON.parse(m[1]))
 assert.ok(data.some(x=>x['@type']==='BlogPosting'),post.slug.current+': article schema')
 assert.ok(!/href=["'](?:javascript|data):/i.test(article),post.slug.current+': no unsafe link protocols')
 if(post.slug.current==='your-ai-is-a-caged-genius-here-s-how-to-set-it-free') assert.ok(article.includes('youtube-nocookie.com/embed/'),'original YouTube block renders')
}
assert.equal((await fetch(base+'/blog/this-article-does-not-exist')).status,404,'unknown slug')
const matched=await (await fetch(base+'/api/blog/search?q=RAG&pageSize=-1&page=NaN')).json()
assert.ok(matched.posts.length<=6,'invalid pagination values fall back to safe defaults')
const empty=await fetch(base+'/blog?q=nonexistent-article-query-98453')
assert.ok((await empty.text()).includes('No articles match'),'empty search state')
const feed=await fetch(base+'/blog/feed.xml')
assert.equal(feed.status,200)
assert.ok(feed.headers.get('content-type').includes('application/rss+xml'))
const xml=await feed.text();assert.equal((xml.match(/<item>/g)||[]).length,search.total,'RSS includes all published articles')
const sitemap=await (await fetch(base+'/sitemap.xml')).text()
for(const post of search.posts)assert.ok(sitemap.includes('/blog/'+post.slug.current),'sitemap includes '+post.slug.current)
const studio=await fetch(base+'/studio')
assert.equal(studio.status,200,'Studio route renders')
assert.ok((await studio.text()).includes('noindex'),'Studio is not indexed')
console.log(`PASS: ${search.total} original Sanity articles, server rendering, schema, search, pagination, video, missing-post 404, RSS, sitemap, and Studio route.`)
console.log('Studio login/edit/publish requires an authenticated Sanity project member; this test does not verify authoring access.')
